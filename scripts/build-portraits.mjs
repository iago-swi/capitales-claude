/**
 * Turns the credit portraits into a TypeScript module of data URIs.
 *
 * The photos have to travel inside the bundle: the APK and the single HTML
 * file have nowhere to fetch from, and a credits screen that only works with a
 * server is not a credits screen. So they are cropped square, scaled to a size
 * that survives a phone's pixel density, and inlined.
 *
 * Run it again whenever a portrait changes:
 *   node scripts/build-portraits.mjs
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const SOURCE = path.join(ROOT, 'assets', 'portraits');
const OUT = path.join(ROOT, 'packages', 'ui', 'src', 'portraits.ts');

/**
 * 256 rather than 160: the bubble is drawn at ~132 CSS pixels and a phone puts
 * two or three device pixels in each of those, so a 160 source would arrive
 * visibly soft on the one platform most likely to see it.
 */
const SIZE = 256;

/**
 * `gravity` is per photo because a centred crop is wrong for two of the three.
 * Philippe's joke is the shrub above his head and the north edge keeps it;
 * Claude's stock portrait puts the face high in the frame and the same edge
 * keeps him from being a picture of folded arms.
 */
const PEOPLE = [
  { key: 'philippe', file: '1-Philippe.jpg', gravity: 'north' },
  { key: 'raphael', file: '2-Raphael.jpg', gravity: 'centre' },
  { key: 'claude', file: '3-Claude.jpg', gravity: 'north' },
];

const entries = [];
for (const { key, file, gravity } of PEOPLE) {
  const src = path.join(SOURCE, file);
  const buf = await sharp(src)
    .resize(SIZE, SIZE, { fit: 'cover', position: gravity })
    .webp({ quality: 82 })
    .toBuffer();

  entries.push({ key, kb: buf.length / 1024, uri: `data:image/webp;base64,${buf.toString('base64')}` });
  console.log(`${key.padEnd(10)} ${file.padEnd(18)} ${gravity.padEnd(7)} ${(buf.length / 1024).toFixed(1)} kB`);
}

const total = entries.reduce((n, e) => n + e.kb, 0);
console.log(`\ntotal inlined: ${total.toFixed(1)} kB`);

const body = `/**
 * Credit portraits, inlined.
 *
 * GENERATED by scripts/build-portraits.mjs — do not edit by hand. The sources
 * live in assets/portraits/; run the script again after changing one.
 *
 * ${SIZE}x${SIZE} WebP, ${total.toFixed(1)} kB in total. They are data URIs because every
 * build has to work with no network: the APK and the single HTML file have
 * nowhere to fetch from.
 */

${entries.map((e) => `export const ${e.key.toUpperCase()}_PORTRAIT =\n  '${e.uri}';`).join('\n\n')}
`;

writeFileSync(OUT, body, 'utf8');
console.log(`\n-> ${path.relative(ROOT, OUT)}`);
